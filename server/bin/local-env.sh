    if [[ -n "${DANA_LOCAL_ENV_EXTRA:-}" ]]; then
        echo "==> Appending $DANA_LOCAL_ENV_EXTRA"
        { echo "# From DANA_LOCAL_ENV_EXTRA"; cat "$DANA_LOCAL_ENV_EXTRA"; } >> "$STATE/app.env"
    fi
    chmod 600 "$STATE/app.env"
}

seed() {
    local source=/fixtures/db_8_1_0.sql mounts=(-v "$ROOT/tests/fixtures:/fixtures:ro")
    if [[ -n "${DANA_LOCAL_DB:-}" ]]; then
        source=/seed/db.sqlite3
        mounts=(-v "$(cd "$(dirname "$DANA_LOCAL_DB")" && pwd)/$(basename "$DANA_LOCAL_DB"):/seed/db.sqlite3:ro")
    fi
    echo "==> Seeding the data volume (only when it has no database yet) from ${DANA_LOCAL_DB:-tests/fixtures/db_8_1_0.sql}"
    compose run --rm --no-deps --user root "${mounts[@]}" --entrypoint python app -c "
import os, pathlib, shutil, sqlite3, sys
db = pathlib.Path('/app/db/db.sqlite3')
src = '$source'
if db.exists():
    print('    database already there: not seeded')
elif src.endswith('.sql'):
    con = sqlite3.connect(db); con.executescript(open(src).read()); con.close()
    print('    loaded', src)
else:
    shutil.copyfile(src, db)
    print('    copied', src)
for p in [db.parent, *db.parent.rglob('*')]:
    os.chown(p, 1001, 1001)
"
}

wait_healthy() {
    echo -n "==> Waiting for the app to be healthy"
    for _ in $(seq 1 120); do
        status="$(docker inspect -f '{{.State.Health.Status}}' "$(compose ps -q app)" 2>/dev/null || true)"
        if [[ "$status" == "healthy" ]]; then echo " ok"; return 0; fi
        if [[ "$(docker inspect -f '{{.State.Running}}' "$(compose ps -q app)" 2>/dev/null)" == "false" ]]; then
            echo; echo "The app exited:"; compose logs --tail 40 app; return 1
        fi
        echo -n "."; sleep 2
    done
    echo; echo "The app did not become healthy:"; compose logs --tail 40 app; return 1
}

up() {
    if [[ "${DANA_LOCAL_SOURCE:-}" == "1" ]] && docker image inspect "$IMAGE" >/dev/null 2>&1; then
        echo "==> Using the existing $IMAGE with the working tree's code (DANA_LOCAL_SOURCE=1)"
        build_worker
    else
        build
    fi
    generate_env
    seed
    echo "==> Starting"
    compose up -d
    wait_healthy
    local token
    token="$(grep '^API_TOKEN=' "$STATE/app.env" | cut -d= -f2-)"
    echo
    echo "Dana (local) is up: http://127.0.0.1:$PORT  (log in with the admin token: $token)"
    echo "Second test user: run 'bin/local-env.sh test' once; its token is then in $STATE/users.json"
}

case "${1:-}" in
    up) up ;;
    build) build ;;
    test) shift; exec "$(python_bin)" "$ENV_DIR/e2e.py" "$@" ;;
    logs) shift; compose logs "${@:--f}" app ;;
    ps) compose ps ;;
    down) compose down -v --remove-orphans; rm -rf "$STATE"; echo "==> Removed containers, networks, volume and $STATE" ;;
    reset) compose down -v --remove-orphans; rm -rf "$STATE"; up ;;
    # The worker shares the app's network namespace: it restarts with it.
    restart) compose restart app; [[ "${DANA_LOCAL_MONEY:-}" == "1" ]] && compose restart bank-worker; wait_healthy ;;
    *) sed -n '2,26p' "$0"; exit 2 ;;
esac
