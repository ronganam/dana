#!/usr/bin/env bash
# Local test environment: the real image + stub services, started from the 9.0
# database so the first start is the real upgrade (docs/local-testing.md).
#
#   bin/local-env.sh up      build the image, generate the env file, seed the data volume, start,
#                            connect the admin's addons to the stubs (bin/dana, as an operator does)
#   bin/local-env.sh test    run the end-to-end script against the running environment
#   bin/local-env.sh logs    follow the app's log (extra args go to `docker compose logs`)
#   bin/local-env.sh ps      the containers
#   bin/local-env.sh down    remove containers, networks, the data volume and the generated state
#   bin/local-env.sh reset   down, then up
#   bin/local-env.sh restart restart the app (with DANA_LOCAL_SOURCE=1: runs your latest code, no rebuild)
#   bin/local-env.sh exec …  run a command in the app container (exec python bin/dana users list)
#
# Environment (all optional):
#   DANA_LOCAL_PORT          web UI / API on 127.0.0.1 (default 18080)
#   DANA_LOCAL_NAME          the environment's name: its compose project, image dana-local/<name>:latest and
#                            state folder tests/local_env/.state-<name> (default dana-local on port 18080, with
#                            image dana-local/app:latest and .state; else dana-local-<port>)
#   DANA_LOCAL_CONTROL_PORT  the stubs' control API on 127.0.0.1 (default 18090 on port 18080, else port+100)
#   DANA_LOCAL_DB            seed from this SQLite file (a copy of a real database) instead of the
#                            9.0 fixture; see docs/local-testing.md before using it
#   DANA_LOCAL_ENV_EXTRA     file of KEY=value lines appended to the generated env (they win)
#   DANA_LOCAL_EGRESS=1      let the app reach the internet (needed for a real model key)
#   DANA_LOCAL_SOURCE=1      run the working tree's code (mounted read-only) instead of the image's
#                            copy; `up` builds only when the image is missing, `restart` reloads code
#   DANA_LOCAL_ADDONS        NAME=PATH[:NAME=PATH…]: addon folders mounted read-only as site addons
#                            (/app/addons-site/NAME); what `bin/dana addons dev` uses
#
# Nothing here talks to production: no registry push, no kubectl; the app has no
# route out of the machine unless DANA_LOCAL_EGRESS=1.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="$ROOT/tests/local_env"
# Several environments run side by side when each has its own port (or name): the
# name gives the compose project (containers, network, volume), the image tag and
# the state folder; the port gives the control port. Port 18080 keeps the plain names.
PORT="${DANA_LOCAL_PORT:-18080}"
if [[ "$PORT" == "18080" ]]; then
    NAME="${DANA_LOCAL_NAME:-dana-local}"
    CONTROL_PORT="${DANA_LOCAL_CONTROL_PORT:-18090}"
else
    NAME="${DANA_LOCAL_NAME:-dana-local-$PORT}"
    CONTROL_PORT="${DANA_LOCAL_CONTROL_PORT:-$((PORT + 100))}"
fi
if [[ "$NAME" == "dana-local" ]]; then
    STATE_DIR=.state
    IMAGE="${DANA_LOCAL_IMAGE:-dana-local/app:latest}"
else
    STATE_DIR=".state-$NAME"
    IMAGE="${DANA_LOCAL_IMAGE:-dana-local/$NAME:latest}"
fi
STATE="$ENV_DIR/$STATE_DIR"
export DANA_LOCAL_NAME="$NAME" DANA_LOCAL_IMAGE="$IMAGE" DANA_LOCAL_PORT="$PORT" \
    DANA_LOCAL_CONTROL_PORT="$CONTROL_PORT" DANA_LOCAL_STATE="$STATE_DIR"

compose() {
    local files=(-f "$ENV_DIR/compose.yaml")
    if [[ "${DANA_LOCAL_EGRESS:-}" == "1" ]]; then
        files+=(-f "$ENV_DIR/compose.egress.yaml")
    fi
    if [[ "${DANA_LOCAL_SOURCE:-}" == "1" ]]; then
        files+=(-f "$ENV_DIR/compose.source.yaml")
    fi
    if [[ -n "${DANA_LOCAL_ADDONS:-}" ]]; then
        addons_override
        files+=(-f "$STATE/compose.addons.yaml")
    fi
    docker compose "${files[@]}" "$@"
}

# DANA_LOCAL_ADDONS=NAME=PATH[:…] → a compose override mounting each folder as a site addon.
addons_override() {
    mkdir -p "$STATE"
    {
        echo "# Generated by bin/local-env.sh from DANA_LOCAL_ADDONS: addon folders mounted as site addons."
        echo "services:"
        echo "  app:"
        echo "    volumes:"
        local entry name path
        IFS=':' read -ra entries <<<"$DANA_LOCAL_ADDONS"
        for entry in "${entries[@]}"; do
            name="${entry%%=*}"
            path="$(cd "${entry#*=}" && pwd)"
            echo "      - \"$path:/app/addons-site/$name:ro\""
        done
    } > "$STATE/compose.addons.yaml"
}

python_bin() {
    if [[ -x "$ROOT/.venv/bin/python" ]]; then echo "$ROOT/.venv/bin/python"; else echo python3; fi
}

build() {
    echo "==> Building $IMAGE from the Dockerfile (context: the files git tracks or would add, as bin/deploy builds it)"
    cd "$ROOT"
    git ls-files -z --cached --others --exclude-standard \
        | tar --null --ignore-failed-read -T - -cf - 2>/dev/null \
        | docker build -t "$IMAGE" -f Dockerfile -
}

in_image() {
    docker run --rm --network none "$IMAGE" python -c "$1"
}

generate_env() {
    mkdir -p "$STATE"
    if [[ -f "$STATE/app.env" ]]; then
        echo "==> Keeping $STATE/app.env"
        return
    fi
    echo "==> Generating $STATE/app.env (throwaway values for this environment only)"
    local key api_token tg_token publish waha_secret
    key="$(in_image 'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())')"
    api_token="local-admin-$(in_image 'import secrets; print(secrets.token_hex(12))')"
    tg_token="900000001:$(in_image 'import secrets; print(secrets.token_urlsafe(26))')"
    publish="local-publish-$(in_image 'import secrets; print(secrets.token_hex(8))')"
    waha_secret="local-waha-hmac-$(in_image 'import secrets; print(secrets.token_hex(12))')"
    # Server-wide values and the first user's profile (core/user_rows.py); the
    # addons' accounts are connected after the start (connect_addons).
    cat > "$STATE/app.env" <<EOF
# Generated by bin/local-env.sh: throwaway values for the local test environment.
DATABASE_PATH=/app/db/db.sqlite3
PORT=8080
TIMEZONE=Asia/Jerusalem
API_TOKEN=$api_token
# With API_TOKEN set this only lets UnifiedPush pings go to the plain-http ntfy stub.
DANA_INSECURE_DEV=1
CREDENTIALS_KEY=$key
APP_PUBLISH_TOKEN=$publish
APP_RELEASES_REPO=
WAHA_WEBHOOK_SECRET=$waha_secret
TELEGRAM_BOT_TOKEN=$tg_token
TELEGRAM_API_BASE=http://stubs:8081
ALLOWED_TELEGRAM_USER_IDS=111111111
TELEGRAM_CHAT_ID=111111111
OWNER_NAME=Robin
OWNER_CONTEXT=Robin lives in Tel Aviv and works as an architect. Noa is Robin's sister.
GOOGLE_CLIENT_ID=local-client.apps.googleusercontent.com
GOOGLE_CLIENT_SECRET=local-client-secret
MEMBER_ALLOWED_ORIGINS=homeassistant=http://stubs:8124
MODEL=openai/dana-local-chat
BACKGROUND_MODEL=openai/dana-local-background
TRANSCRIBE_MODEL=openai/whisper-1
ASSISTANT_MODELS=[{"id": "fast", "label": "Fast", "model": "openai/dana-local-fast", "description": "Local fake model."}, {"id": "balanced", "label": "Balanced", "model": "openai/dana-local-balanced", "reasoning_effort": "medium", "description": "Local fake model with reasoning."}, {"id": "deep", "label": "Deep", "model": "openai/dana-local-deep", "reasoning_effort": "high", "description": "Local fake model."}]
OPENAI_API_BASE=http://stubs:9100/v1
OPENAI_API_KEY=sk-local-fake
LITELLM_LOCAL_MODEL_COST_MAP=True
EOF
    if [[ -n "${DANA_LOCAL_ENV_EXTRA:-}" ]]; then
        echo "==> Appending $DANA_LOCAL_ENV_EXTRA"
        { echo "# From DANA_LOCAL_ENV_EXTRA"; cat "$DANA_LOCAL_ENV_EXTRA"; } >> "$STATE/app.env"
    fi
    chmod 600 "$STATE/app.env"
}

seed() {
    local source=/fixtures/db_9_0.sql mounts=(-v "$ROOT/tests/fixtures:/fixtures:ro")
    if [[ -n "${DANA_LOCAL_DB:-}" ]]; then
        source=/seed/db.sqlite3
        mounts=(-v "$(cd "$(dirname "$DANA_LOCAL_DB")" && pwd)/$(basename "$DANA_LOCAL_DB"):/seed/db.sqlite3:ro")
    fi
    echo "==> Seeding the data volume (only when it has no database yet) from ${DANA_LOCAL_DB:-tests/fixtures/db_9_0.sql}"
    compose run --rm --no-deps --user root "${mounts[@]}" --entrypoint python app -c "
import os, pathlib, shutil, sqlite3, sys
db = pathlib.Path('/app/db/db.sqlite3')
src = '$source'
if db.exists():
    print('    database already there: not seeded')
elif src.endswith('.sql'):
    con = sqlite3.connect(db); con.executescript(open(src).read())
    # The fixture's first admin as 9.0 made them from this env (name, context, Telegram ids).
    con.execute(\"UPDATE users SET name = 'Robin', other_names = '', telegram_chat_id = 111111111, \"
                \"context = 'Robin lives in Tel Aviv and works as an architect. Noa is Robin''s sister.'\")
    con.execute('INSERT OR IGNORE INTO user_telegram (telegram_user_id, user_id, created_at) '
                'SELECT 111111111, id, created_at FROM users')
    con.commit(); con.close()
    print('    loaded', src)
else:
    shutil.copyfile(src, db)
    print('    copied', src)
for p in [db.parent, *db.parent.rglob('*')]:
    os.chown(p, 1001, 1001)
"
}

wait_healthy() {
    echo -n "==> Waiting for the app to be healthy"
    for _ in $(seq 1 120); do
        status="$(docker inspect -f '{{.State.Health.Status}}' "$(compose ps -q app)" 2>/dev/null || true)"
        if [[ "$status" == "healthy" ]]; then echo " ok"; return 0; fi
        if [[ "$(docker inspect -f '{{.State.Running}}' "$(compose ps -q app)" 2>/dev/null)" == "false" ]]; then
            echo; echo "The app exited:"; compose logs --tail 40 app; return 1
        fi
        echo -n "."; sleep 2
    done
    echo; echo "The app did not become healthy:"; compose logs --tail 40 app; return 1
}

# The admin's addons, pointed at the stubs (the stub credentials are throwaway
# values that tests/local_env/e2e.py knows too). Skipped for one already connected.
connect_addons() {
    echo "==> Connecting the admin's addons to the stubs (bin/dana addons connect)"
    _connect homeassistant 'host=http://stubs:8123\ntoken=local-ha-token-a\n' \
        phone_battery_sensor=sensor.robin_phone_battery
    _connect whatsapp 'url=http://stubs:3000/api\napi_key=local-waha-key\nsession=default\n' \
        voice_telegram_chat_id=111111111
    _connect calendar 'refresh_token=local-google-refresh-token\n' calendar_id=primary
    _connect cameras '' url=http://stubs:5000
    _connect ops ''
}

_connect() {
    local addon="$1" creds="$2" out
    shift 2
    local args=(addons connect Robin "$addon" "$@")
    [[ -n "$creds" ]] && args+=(--credentials-stdin)
    if out="$(printf '%b' "$creds" | compose exec -T app bin/dana "${args[@]}" 2>&1)"; then
        echo "    $addon connected"
    elif grep -q "already" <<<"$out"; then
        echo "    $addon already connected"
    else
        echo "$out"
        return 1
    fi
}

up() {
    if [[ "${DANA_LOCAL_SOURCE:-}" == "1" ]] && docker image inspect "$IMAGE" >/dev/null 2>&1; then
        echo "==> Using the existing $IMAGE with the working tree's code (DANA_LOCAL_SOURCE=1)"
    else
        build
    fi
    generate_env
    seed
    echo "==> Starting"
    compose up -d
    wait_healthy
    connect_addons
    local token
    token="$(grep '^API_TOKEN=' "$STATE/app.env" | cut -d= -f2-)"
    echo
    echo "Dana (local) is up: http://127.0.0.1:$PORT  ($NAME; log in with the admin token: $token)"
    echo "Second test user: run 'bin/local-env.sh test' once; its token is then in $STATE/users.json"
}

case "${1:-}" in
    up) up ;;
    build) build ;;
    test) shift; exec "$(python_bin)" "$ENV_DIR/e2e.py" "$@" ;;
    logs) shift; compose logs "${@:--f}" app ;;
    ps) compose ps ;;
    down) compose down -v --remove-orphans; rm -rf "$STATE"; echo "==> Removed containers, networks, volume and $STATE" ;;
    reset) compose down -v --remove-orphans; rm -rf "$STATE"; up ;;
    restart) compose restart app; wait_healthy ;;
    exec) shift; compose exec -T app "$@" ;;
    *) sed -n '2,31p' "$0"; exit 2 ;;
esac
