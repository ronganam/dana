#!/usr/bin/env bash
# Local test environment: the real image + stub services, started from the 8.1.0
# database so the first start is the real upgrade (docs/local-testing.md).
#
#   bin/local-env.sh up      build the image, generate the env file, seed the data volume, start
#   bin/local-env.sh test    run the end-to-end script against the running environment
#   bin/local-env.sh logs    follow the app's log (extra args go to `docker compose logs`)
#   bin/local-env.sh ps      the containers
#   bin/local-env.sh down    remove containers, networks, the data volume and the generated state
#   bin/local-env.sh reset   down, then up
#   bin/local-env.sh restart restart the app (with DANA_LOCAL_SOURCE=1: runs your latest code, no rebuild)
#
# Environment (all optional):
#   DANA_LOCAL_PORT          web UI / API on 127.0.0.1 (default 18080)
#   DANA_LOCAL_CONTROL_PORT  the stubs' control API on 127.0.0.1 (default 18090)
#   DANA_LOCAL_DB            seed from this SQLite file (a copy of a real database) instead of the
#                            8.1.0 fixture; see docs/local-testing.md before using it
#   DANA_LOCAL_ENV_EXTRA     file of KEY=value lines appended to the generated env (they win)
#   DANA_LOCAL_EGRESS=1      let the app reach the internet (needed for a real model key)
#   DANA_LOCAL_SOURCE=1      run the working tree's code (mounted read-only) instead of the image's
#                            copy; `up` builds only when the image is missing, `restart` reloads code
#   DANA_LOCAL_MONEY=1       also run the bank-worker sidecar (built from bank-worker/); the real bank
#                            sites need DANA_LOCAL_EGRESS=1 as well (docs/money.md)
#
# Nothing here talks to production: no registry push, no kubectl; the app has no
# route out of the machine unless DANA_LOCAL_EGRESS=1.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="$ROOT/tests/local_env"
STATE="$ENV_DIR/.state"
IMAGE="${DANA_LOCAL_IMAGE:-dana-local/app:latest}"
PORT="${DANA_LOCAL_PORT:-18080}"
export DANA_LOCAL_IMAGE="$IMAGE" DANA_LOCAL_PORT="$PORT" DANA_LOCAL_CONTROL_PORT="${DANA_LOCAL_CONTROL_PORT:-18090}"

compose() {
    local files=(-f "$ENV_DIR/compose.yaml")
    if [[ "${DANA_LOCAL_EGRESS:-}" == "1" ]]; then
        files+=(-f "$ENV_DIR/compose.egress.yaml")
    fi
    if [[ "${DANA_LOCAL_SOURCE:-}" == "1" ]]; then
        files+=(-f "$ENV_DIR/compose.source.yaml")
    fi
    if [[ "${DANA_LOCAL_MONEY:-}" == "1" ]]; then
        files+=(-f "$ENV_DIR/compose.money.yaml")
    fi
    docker compose "${files[@]}" "$@"
}

python_bin() {
    if [[ -x "$ROOT/.venv/bin/python" ]]; then echo "$ROOT/.venv/bin/python"; else echo python3; fi
}

build() {
    echo "==> Building $IMAGE from the Dockerfile (context: the files git tracks or would add, as bin/deploy builds it)"
    cd "$ROOT"
    git ls-files -z --cached --others --exclude-standard \
        | tar --null --ignore-failed-read -T - -cf - 2>/dev/null \
        | docker build -t "$IMAGE" -f Dockerfile -
    build_worker
}

build_worker() {
    [[ "${DANA_LOCAL_MONEY:-}" == "1" ]] || return 0
    local image="${DANA_LOCAL_WORKER_IMAGE:-dana-local/bank-worker:latest}"
    echo "==> Building $image from bank-worker/"
    docker build -q -t "$image" "$ROOT/bank-worker" >/dev/null
}

in_image() {
    docker run --rm --network none "$IMAGE" python -c "$1"
}

generate_env() {
    mkdir -p "$STATE"
    if [[ -f "$STATE/app.env" ]]; then
        echo "==> Keeping $STATE/app.env"
        return
    fi
    echo "==> Generating $STATE/app.env (throwaway values for this environment only)"
    local key api_token tg_token publish
    key="$(in_image 'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())')"
    api_token="local-admin-$(in_image 'import secrets; print(secrets.token_hex(12))')"
    tg_token="900000001:$(in_image 'import secrets; print(secrets.token_urlsafe(26))')"
    publish="local-publish-$(in_image 'import secrets; print(secrets.token_hex(8))')"
    # Shaped like production's env before the upgrade: every name the one-time
    # import reads (addons/bootstrap.py, core/user_rows.py), pointing at the stubs.
    cat > "$STATE/app.env" <<EOF
# Generated by bin/local-env.sh: throwaway values for the local test environment.
DATABASE_PATH=/app/db/db.sqlite3
PORT=8080
TIMEZONE=Asia/Jerusalem
API_TOKEN=$api_token
CREDENTIALS_KEY=$key
APP_PUBLISH_TOKEN=$publish
INTERNAL_HOSTS=ganam-assistant.ganam-assistant,ganam-assistant.ganam-assistant.svc.cluster.local
TELEGRAM_BOT_TOKEN=$tg_token
TELEGRAM_API_BASE=http://stubs:8081
ALLOWED_TELEGRAM_USER_IDS=111111111
TELEGRAM_CHAT_ID=111111111
OWNER_NAME=Robin
OWNER_CONTEXT=Robin lives in Tel Aviv and works as an architect. Noa is Robin's sister.
HOMEASSISTANT_HOST=http://stubs:8123
HOMEASSISTANT_TOKEN=local-ha-token-a
PRIMARY_PERSON=person.robin
PHONE_INTERACTIVE_SENSOR=binary_sensor.robin_phone_interactive
PHONE_BATTERY_SENSOR=sensor.robin_phone_battery
PHONE_NOTIFY_SERVICE=mobile_app_robin_phone
BRIEFING_WEATHER_ENTITY=weather.forecast_home
HOMEASSISTANT_TODO_ENTITY_ID=todo.dana
WAHA_URL=http://stubs:3000/api/
WAHA_API_KEY=local-waha-key
WAHA_SESSION=default
WHATSAPP_VOICE_TELEGRAM_CHAT_ID=111111111
GOOGLE_CLIENT_ID=local-client.apps.googleusercontent.com
GOOGLE_CLIENT_SECRET=local-client-secret
GOOGLE_REFRESH_TOKEN=local-google-refresh-token
GOOGLE_CALENDAR_ID=primary
FRIGATE_URL=http://stubs:5000
MEMBER_ALLOWED_ORIGINS=homeassistant=http://stubs:8124
MODEL=openai/dana-local-chat
BACKGROUND_MODEL=openai/dana-local-background
TRANSCRIBE_MODEL=openai/whisper-1
ASSISTANT_MODELS=[{"id": "fast", "label": "Fast", "model": "openai/dana-local-fast", "description": "Local fake model."}, {"id": "balanced", "label": "Balanced", "model": "openai/dana-local-balanced", "reasoning_effort": "medium", "description": "Local fake model with reasoning."}, {"id": "deep", "label": "Deep", "model": "openai/dana-local-deep", "reasoning_effort": "high", "description": "Local fake model."}]
