package io.github.ronganam.dana.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Spacing on an 8dp rhythm (4dp steps where a row needs them). Screens use
 * [screen] (16dp margins) horizontally; groups use [lg] inside.
 */
object Space {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val screen = 16.dp
    val minTouch = 48.dp
}
